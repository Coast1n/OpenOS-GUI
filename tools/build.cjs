const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { bundle, unbundleString } = require('luabundle');
const lua = require('moonsharp-luaparse');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist');
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const relative = file => path.relative(root, file).split(path.sep).join('/');
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(item => {
    const file = path.join(dir, item.name);
    return item.isDirectory() ? walk(file) : file.endsWith('.lua') ? [file] : [];
  }).sort();
}
const sources = walk(path.join(root, 'lib')).filter(file => relative(file) === 'lib/ocgui.lua' || relative(file).startsWith('lib/ocgui/'));
const expected = sources.map(file => relative(file).replace(/^lib\//, '').replace(/\.lua$/, '').replaceAll('/', '.'));
const license = fs.readFileSync(require.resolve('luabundle/LICENSE'), 'utf8');
const header = '-- Generated by tools/build.cjs; edit lib/ or examples/ instead.\n'
  + '-- luabundle runtime license:\n' + license.split(/\r?\n/).map(line => '-- ' + line).join('\n') + '\n';
const outputs = [];
const generated = [];
for (const [entry, filename, rootModuleName] of [
  ['lib/ocgui.lua', 'ocgui.lua', 'ocgui'],
  ['examples/basic.lua', 'basic.lua', '__basic']
]) {
  const content = header + bundle(path.join(root, entry), {
    luaVersion: '5.3', isolate: false, metadata: true, rootModuleName,
    paths: [path.join(root, 'lib', '?.lua')],
    expressionHandler(module) {
      // Only the existing lazy OpenOS service loader has a dynamic require.
      if (module.name !== 'ocgui.platform.openos') throw Error('Unexpected dynamic require in ' + module.name);
    }
  });
  lua.parse(content, { luaVersion: '5.3' });
  const names = Object.keys(unbundleString(content).modules).sort();
  const wanted = (entry.startsWith('examples/') ? expected.concat(rootModuleName) : expected).sort();
  if (JSON.stringify(names) !== JSON.stringify(wanted)) throw Error('Module inventory mismatch: ' + filename);
  generated.push([filename, content]);
  outputs.push({ file: filename, entry, bytes: Buffer.byteLength(content), sha256: hash(content), modules: names });
}
// Write only after both outputs pass parsing and module inventory checks.
fs.mkdirSync(out, { recursive: true });
for (const [filename, content] of generated) fs.writeFileSync(path.join(out, filename), content);
fs.writeFileSync(path.join(out, 'THIRD-PARTY-LICENSES.txt'), 'luabundle 1.7.0\nhttps://github.com/Benjamin-Dobell/luabundle\n\n' + license);
const manifest = {
  version: '0.1.0-dev', luaVersion: '5.3', bundler: 'luabundle@1.7.0',
  runtimeExternals: ['term', 'unicode', 'component', 'event', 'computer'],
  verification: 'Lua 5.3 syntax and module inventory checked; bundled OpenOS runtime verification pending.',
  lockSha256: hash(fs.readFileSync(path.join(root, 'package-lock.json'))),
  sources: sources.concat(path.join(root, 'examples', 'basic.lua')).map(file => ({ file: relative(file), sha256: hash(fs.readFileSync(file)) })),
  outputs
};
fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
for (const item of outputs) console.log(`${item.file}: ${item.bytes} bytes, ${item.modules.length} modules, SHA-256 ${item.sha256}`);
