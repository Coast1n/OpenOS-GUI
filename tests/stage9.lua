end)
test("A18 callback errors stop input and remain available to the host", function()
  withApp(function(app)
    local b = addButton(app); b:on("pointer_down", function() error("callback boom", 0) end); assert(app:open())
    local ok, err = pointer(app); eq(ok, nil); eq(err.code, "callback_failed"); eq(err.message, "callback boom")
    eq(app:isActive(), false); eq(b:isPressed(), false)
    local again, same = app:dispatch(); eq(again, nil); eq(same, err)
  end)
end)
test("A19 GPU rendering errors keep their structured device code", function()
  withApp(function(app, _, state)
