-- Host lifecycle checks with injected OpenOS services.
local root = (...) or "."
assert(_VERSION == "Lua 5.3", "BLOCKED: Lua 5.3 required")
local import = assert(loadfile(root .. "/tests/support/loader.lua"))()(root)
local widget, container = import("ocgui.widget"), import("ocgui.container")
local button = import("ocgui.button")
local dispatcher, interaction = import("ocgui.dispatcher"), import("ocgui.interaction")
local report = {suite = "STAGE9-APPLICATION-001", lua = _VERSION, passed = 0, failed = 0, cases = {}}
local function eq(a, b) assert(a == b, "expected " .. tostring(b) .. ", got " .. tostring(a)) end
local function rejects(fn) local ok = pcall(fn); eq(ok, false) end
local function approx(a, b) assert(math.abs(a - b) < 0.000001, "numeric mismatch") end
local function test(name, fn)
  local ok, err = pcall(fn)
  report[ok and "passed" or "failed"] = report[ok and "passed" or "failed"] + 1
  report.cases[#report.cases + 1] = {name = name, passed = ok, error = not ok and tostring(err) or nil}
  print((ok and "PASS " or "FAIL ") .. name .. (ok and "" or ": " .. tostring(err)))
end
local application = import("ocgui.application")
local label = import("ocgui.label")
local fake = assert(loadfile(root .. "/tests/support/fake_openos.lua"))()
local unicode = require("unicode")
local function withApp(fn)
  local services, gpu, state = fake(unicode)
  local now, pulls = 0, 0
  services.computer.uptime = function() return now end
  services.event.pull = function() pulls = pulls + 1; error("host lifecycle must not pull events") end
  local app = application.new(nil, services)
  local ok, err = pcall(fn, app, gpu, state, services, function(value) now = value end, function() return pulls end)
  local closed, closeErr = app:close()
  if not ok then error(err, 0) end
  assert(closed, closeErr and closeErr.message)
end
local function addButton(app)
  return app.root:add(button.new {x = 2, y = 2, width = 8, height = 2, text = "OK"})
end
local function pointer(app, kind, x, y)
  return app:dispatch(kind or "touch", "screen-test", x or 2, y or 2, 0, "p")
end
local function key(app, kind, code, source)
  return app:dispatch(kind, source or "keyboard-test", 0, code, "p")
end
local function count(state, name)
  local total = 0
  for _, call in ipairs(state.calls) do if call.name == name then total = total + 1 end end
  return total
end

test("A01 construction is lazy and exposes a read-only root", function()
  withApp(function(app, _, state, _, _, pulls)
    eq(#state.calls, 0); eq(pulls(), 0); eq(app:isActive(), false)
    local x, y, w, h = app.root:getBounds(); eq(x, 1); eq(y, 1); eq(w, 1); eq(h, 1)
    rejects(function() app.root = container.new() end)
  end)
end)
test("A02 invalid options GPU and theme fail before acquiring devices", function()
  for _, options in ipairs({false, {extra = true}, {gpu = 1}, {theme = {label = {foreground = -1}}}}) do
    rejects(function() application.new(options) end)
  end
end)
test("A03 application root flags bounds and attachment are protected", function()
  withApp(function(app)
    rejects(function() app.root:setBounds(2, 2, 3, 3) end)
    rejects(function() app.root:setVisible(false) end)
    rejects(function() app.root:setEnabled(false) end)
    rejects(function() container.new():add(app.root) end)
  end)
end)
test("A04 open sizes the root without discarding prebuilt children", function()
  withApp(function(app)
    local b = addButton(app); assert(app:open()); eq(app:isActive(), true)
    local x, y, w, h = app.root:getBounds(); eq(x, 1); eq(y, 1); eq(w, 20); eq(h, 10)
    eq(b:getParent(), app.root)
  end)
end)
test("A05 open neither paints nor consumes an event", function()
  withApp(function(app, _, state, _, _, pulls)
    assert(app:open()); eq(count(state, "fill"), 0); eq(count(state, "set"), 0); eq(pulls(), 0)
  end)
end)
test("A06 render merges invalidation and skips idle drawing", function()
  withApp(function(app, _, state)
    app.root:add(label.new {text = "X"}); assert(app:open()); assert(app:render())
    local fills, sets = count(state, "fill"), count(state, "set")
    assert(fills > 0 and sets > 0); assert(app:render())
    eq(count(state, "fill"), fills); eq(count(state, "set"), sets)
  end)
end)
test("A07 raw pointer signals activate a button and retain their tuple", function()
  withApp(function(app)
    local b, n = addButton(app), 0
    b:on("click", function(_, e) eq(e.raw.n, 6); eq(e.raw[1], "drop"); eq(e.player, "p"); n = n + 1 end)
    assert(app:open()); pointer(app); eq(b:isPressed(), true)
    pointer(app, "drop"); eq(b:isPressed(), false); eq(n, 1)
  end)
end)
test("A08 raw Enter and Space activate the focused button", function()
  withApp(function(app)
    local b, n = addButton(app), 0; b:on("click", function() n = n + 1 end)
    assert(app:open()); app:setFocus(b)
    for _, code in ipairs({28, 57}) do key(app, "key_down", code); key(app, "key_up", code) end
    eq(n, 2)
  end)
end)
test("A09 foreign and unknown signals do not consume or create input", function()
  withApp(function(app, _, _, _, _, pulls)
    local b, n = addButton(app), 0; b:on("click", function() n = n + 1 end); assert(app:open())
    eq(app:dispatch("touch", "other", 2, 2, 0), false)
    eq(app:dispatch("unknown", nil, 7), false); eq(app:dispatch(), false); eq(n, 0); eq(pulls(), 0)
  end)
end)
test("A10 stop inside up suppresses click and later dispatch", function()
  withApp(function(app)
    local b, n = addButton(app), 0; b:on("click", function() n = n + 1 end)
    b:on("pointer_up", function() app:stop() end); assert(app:open())
    pointer(app); pointer(app, "drop"); eq(n, 0); eq(app:isActive(), false); eq(b:isPressed(), false)
    eq(pointer(app), false); assert(app:render()); eq(app:nextTimeout(), 0); app:stop()
  end)
end)
test("A11 interrupted requests stop and cancels active input", function()
  withApp(function(app)
    local b = addButton(app); assert(app:open()); pointer(app)
    eq(app:dispatch("interrupted"), false); eq(app:isActive(), false); eq(b:isPressed(), false)
  end)
end)
test("A12 dispatch without arguments advances expiration only", function()
  withApp(function(app, _, _, _, clock)
    local b, n = addButton(app), 0; b:on("click", function() n = n + 1 end)
    assert(app:open()); app:setFocus(b); key(app, "key_down", 28); clock(5)
    eq(app:dispatch(), false); eq(b:isPressed(), false); eq(n, 0)
  end)
end)
test("A13 timeout queries respect dirty state and do not expire input", function()
  withApp(function(app, _, _, _, clock)
    local b = addButton(app); assert(app:open()); eq(app:nextTimeout(), 0); assert(app:render())
    eq(app:nextTimeout(), nil); eq(app:nextTimeout(2), 2)
    app:setFocus(b); key(app, "key_down", 28); eq(app:nextTimeout(), 0); assert(app:render())
    clock(4); eq(app:nextTimeout(10), 1); clock(5); eq(app:nextTimeout(), 0)
    eq(b:isPressed(), true); app:dispatch(); eq(b:isPressed(), false)
  end)
end)
test("A14 screen size refresh cancels input and updates root bounds", function()
  withApp(function(app, _, state)
    local b = addButton(app); assert(app:open()); pointer(app)
    state.width, state.height = 30, 12; app:dispatch("screen_resized", "screen-test", 30, 12)
    local _, _, w, h = app.root:getBounds(); eq(w, 30); eq(h, 12); eq(b:isPressed(), false)
    eq(app.root._dirty, true)
  end)
end)
test("A15 component changes refresh accepted keyboard addresses", function()
  withApp(function(app, _, _, services)
    local b = addButton(app); assert(app:open()); app:setFocus(b)
    key(app, "key_down", 28); eq(b:isPressed(), true)
    services.component.invoke = function() return {"keyboard-new"} end
    app:dispatch("component_added", "keyboard-new", "keyboard")
    eq(b:isPressed(), false); eq(app._interaction:getFocus(), nil); app:setFocus(b)
    key(app, "key_down", 28); eq(b:isPressed(), false)
    key(app, "key_down", 28, "keyboard-new"); eq(b:isPressed(), true)
    key(app, "key_up", 28, "keyboard-new"); eq(b:isPressed(), false)
  end)
end)
test("A16 changed screen binding reports device loss and stops", function()
  withApp(function(app, _, state)
    assert(app:open()); state.screen = "other"
    local ok, err = app:dispatch(); eq(ok, nil); eq(err.code, "device_lost"); eq(app:isActive(), false)
    state.screen = "screen-test"
  end)
end)
test("A17 external active-buffer changes report device loss", function()
