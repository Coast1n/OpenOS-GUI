test("A21 close restores device state and releases interaction ownership", function()
  withApp(function(app, _, state)
    local b = addButton(app); assert(app:open()); pointer(app); assert(app:render()); assert(app:close())
    eq(state.buffer, 3); eq(state.colors[0].fg, 2); eq(state.colors[0].fp, true)
    eq(state.colors[0].bg, 5); eq(state.colors[0].bp, true); eq(state.x, 2); eq(state.y, 3); eq(state.blink, true)
    eq(b:isPressed(), false); eq(app.root._interactionOwner, nil); eq(app:isActive(), false)
  end)
end)
test("A22 close-before-open is lazy idempotent and cannot reopen", function()
  withApp(function(app, _, state)
    assert(app:close()); assert(app:close()); eq(#state.calls, 0)
    local ok, err = app:open(); eq(ok, nil); eq(err.code, "invalid_state")
    local drawn, drawErr = app:render(); eq(drawn, nil); eq(drawErr.code, "invalid_state")
  end)
end)
test("A23 another application cannot steal the same GPU", function()
  withApp(function(app, _, _, services)
    assert(app:open()); local other = application.new(nil, services)
    local ok, err = other:open(); eq(ok, nil); eq(err.code, "device_busy")
    eq(app:isActive(), true); assert(app:render()); assert(other:close())
  end)
end)
test("A24 partial platform-open failure restores state and closes", function()
  withApp(function(app, _, state)
    state.fail.getBackground = "once"
    local ok, err = app:open(); eq(ok, nil); eq(err.code, "device_unavailable")
    eq(state.buffer, 3); eq(state.blink, true); eq(app:isActive(), false)
    local again, retryErr = app:open(); eq(again, nil); eq(retryErr.code, "invalid_state")
  end)
end)
test("A25 failure after device-open still rolls back ownership", function()
  withApp(function(app, _, state, services)
    local original = services.component.invoke; services.component.invoke = function() error("keyboard query failed") end
    local ok, err = app:open(); eq(ok, nil); eq(err.code, "device_unavailable"); eq(state.buffer, 3)
    services.component.invoke = original
    local other = application.new(nil, services); assert(other:open()); assert(other:close())
  end)
end)
test("A26 cleanup errors still release ownership and remaining state", function()
  withApp(function(app, _, state, services)
    assert(app:open()); state.fail.setBackground = "once"
    local ok, err = app:close(); eq(ok, nil); eq(err.code, "cleanup_failed"); assert(#err.cleanupErrors > 0)
    eq(state.buffer, 3); eq(state.blink, true); eq(app:isActive(), false); assert(app:close())
    local other = application.new(nil, services); assert(other:open()); assert(other:close())
  end)
end)
test("A27 callbacks cannot recursively dispatch render or close", function()
  withApp(function(app)
    local b = addButton(app); local called = false
    b:on("pointer_down", function()
      for _, method in ipairs({"dispatch", "render", "close"}) do
        local ok, err = app[method](app); eq(ok, nil); eq(err.code, "invalid_state")
      end
      called = true
    end)
    assert(app:open()); pointer(app); eq(called, true); eq(app:isActive(), true)
  end)
end)
test("A28 theme updates copy data and validate before replacement", function()
  withApp(function(app, _, state)
    app.root:add(label.new {text = "X"}); app:setTheme {label = {foreground = 7}}
    assert(app:open()); assert(app:render()); eq(state.colors[0].fg, 7)
    local options = {label = {foreground = 9}}; app:setTheme(options); options.label.foreground = 12
    assert(app:render()); eq(state.colors[0].fg, 9)
    rejects(function() app:setTheme {label = {foreground = -1}} end); eq(app.root._dirty, false)
  end)
end)
test("A29 invalid waits and focus targets throw without stopping", function()
  withApp(function(app)
    rejects(function() app:stop() end); rejects(function() app:setFocus(nil) end)
    assert(app:open()); rejects(function() app:nextTimeout(-1) end)
    rejects(function() app:nextTimeout(math.huge) end)
    rejects(function() app:setFocus(button.new()) end); eq(app:isActive(), true)
  end)
end)
test("A30 missing GPU fails cleanly without acquiring a device", function()
  local services, _, state = fake(unicode); services.term.gpu = function() return nil end
  local app = application.new(nil, services); local ok, err = app:open()
  eq(ok, nil); eq(err.code, "device_unavailable"); eq(#state.calls, 0); assert(app:close())
end)

