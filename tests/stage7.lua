-- Pointer-button checks with an injected clock; no hardware input.
local root = (...) or "."
assert(_VERSION == "Lua 5.3", "BLOCKED: Lua 5.3 required")
local import = assert(loadfile(root .. "/tests/support/loader.lua"))()(root)
local widget, container = import("ocgui.widget"), import("ocgui.container")
local button = import("ocgui.button")
local dispatcher, interaction = import("ocgui.dispatcher"), import("ocgui.interaction")
local report = {suite = "STAGE7-BUTTON-002", lua = _VERSION, passed = 0, failed = 0, cases = {}}
local function eq(a, b) assert(a == b, "expected " .. tostring(b) .. ", got " .. tostring(a)) end
local function rejects(fn) local ok = pcall(fn); eq(ok, false) end
local function approx(a, b) assert(math.abs(a - b) < 0.000001, "numeric mismatch") end
local function test(name, fn)
  local ok, err = pcall(fn)
  report[ok and "passed" or "failed"] = report[ok and "passed" or "failed"] + 1
  report.cases[#report.cases + 1] = {name = name, passed = ok, error = not ok and tostring(err) or nil}
  print((ok and "PASS " or "FAIL ") .. name .. (ok and "" or ": " .. tostring(err)))
end
local function pointer(kind, x, y, button, player, source)
  return {type = kind or "pointer_down", source = source or "screen", screenX = x or 1,
    screenY = y or 1, button = button or 0, player = player}
end
local function key(kind, code, source)
  return {type = kind, source = source or "keyboard-1", code = code, char = 0}
end
local function withManager(fn, oldHook)
  local r = container.new {width = 30, height = 20}
  local a = r:add(button.new {x = 1, width = 3, height = 2, focusable = true})
  local b = r:add(button.new {x = 5, width = 3, height = 2, focusable = true})
  local c = r:add(button.new {x = 9, width = 3, height = 2, focusable = true})
  r._onTreeChanged = oldHook
  local d, time = dispatcher.new(r), 0
  local m = interaction.new(r, d, function() return time end)
  local ok, err = pcall(fn, m, r, a, b, c, function(value) time = value end, d)
  local closed, closeErr = pcall(m.close, m)
  if not ok then error(err, 0) end
  if not closed then error(closeErr, 0) end
end

test("B01 buttons default to focusable and pointer enabled without changing options", function()
  local options = {text = "OK"}; local b = button.new(options)
  eq(b:isFocusable(), true); eq(b:isPressed(), false); eq(b:hitTest(1, 1), b)
  eq(b:getText(), "OK"); eq(options.focusable, nil)
  eq(button.new {focusable = false}:isFocusable(), false)
end)
test("B02 button text validation and setters are inherited", function()
  rejects(function() button.new {text = false} end)
  local b = button.new {text = "old"}; rejects(function() b:setText(nil) end)
  eq(b:getText(), "old"); eq(b:setText("new"), b); eq(b:getText(), "new")
end)
test("B03 right button does not focus capture or activate", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer("pointer_down", 1, 1, 1)); m:route(pointer("pointer_up", 1, 1, 1))
    eq(m:getFocus(), nil); eq(m:getCapture(), nil); eq(a:isPressed(), false); eq(n, 0)
  end)
end)
test("P01 pointer default runs before user down handlers", function()
  withManager(function(m, _, a)
    local called = false
    a:on("pointer_down", function() eq(m:getFocus(), a); eq(m:getCapture(), a); eq(a:isPressed(), true); called = true end)
    m:route(pointer()); eq(called, true)
  end)
end)
test("P02 release clears visual state before up and capture before click", function()
  withManager(function(m, _, a)
    local seen = ""
    a:on("pointer_up", function() eq(a:isPressed(), false); seen = seen .. "up" end)
    a:on("click", function() eq(m:getCapture(), nil); eq(a:isPressed(), false); seen = seen .. "click" end)
    m:route(pointer()); m:route(pointer("pointer_up")); eq(seen, "upclick")
  end)
end)
test("P03 releasing outside does not click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); m:route(pointer("pointer_up", 25, 10))
    eq(n, 0); eq(a:isPressed(), false); eq(m:getCapture(), nil)
  end)
end)
test("P04 dragging out and back changes pressed state and can activate", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); m:route(pointer("pointer_drag", 25, 10)); eq(a:isPressed(), false)
    eq(m:getCapture(), a); m:route(pointer("pointer_drag")); eq(a:isPressed(), true)
    m:route(pointer("pointer_up")); eq(n, 1)
  end)
end)
test("P05 foreign screen player and button cannot release or click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer("pointer_down", 1, 1, 0, "p"))
    m:route(pointer("pointer_up", 1, 1, 0, "p", "other"))
    m:route(pointer("pointer_up", 1, 1, 0, "q")); m:route(pointer("pointer_up", 1, 1, 1, "p"))
    eq(m:getCapture(), a); eq(n, 0)
    m:route(pointer("pointer_up", 1, 1, 0, "p")); eq(n, 1)
  end)
end)
test("P06 disabled overlay blocks the active button below", function()
  withManager(function(m, r, a)
    r:add(button.new {width = 3, height = 2, enabled = false})
    m:route(pointer()); eq(a:isPressed(), false); eq(m:getCapture(), nil)
  end)
end)
test("P07 hiding or disabling cancels the pressed state immediately", function()
  withManager(function(m, _, a)
    m:route(pointer()); a:setVisible(false); eq(a:isPressed(), false); eq(m:getCapture(), nil)
    a:setVisible(true); m:route(pointer()); a:setEnabled(false); eq(a:isPressed(), false)
  end)
end)
test("P08 detachment cancels without preserving a pending click", function()
  withManager(function(m, r, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); r:remove(a); r:add(a); m:route(pointer("pointer_up"))
    eq(a:isPressed(), false); eq(n, 0)
  end)
end)
test("P09 timeout does not activate on a late release", function()
  withManager(function(m, _, a, _, _, clock)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); clock(5); m:route(); eq(a:isPressed(), false)
    m:route(pointer("pointer_up")); eq(n, 0)
  end)
end)
test("P10 failing down handler releases the newly held button", function()
  withManager(function(m, _, a)
    local sentinel = {}; local off = a:on("pointer_down", function() error(sentinel, 0) end)
    local ok, err = pcall(m.route, m, pointer()); eq(ok, false); eq(err, sentinel)
    eq(a:isPressed(), false); eq(m:getCapture(), nil)
    off(); m:route(pointer()); eq(a:isPressed(), true)
  end)
end)
test("P11 failing release handler suppresses click and releases capture", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("pointer_up", function() error("up failed") end)
    m:route(pointer()); rejects(function() m:route(pointer("pointer_up")) end)
    eq(n, 0); eq(m:getCapture(), nil); eq(a:isPressed(), false)
  end)
end)
test("P12 failing click handler leaves no held state", function()
  withManager(function(m, _, a)
    local sentinel = {}; a:on("click", function() error(sentinel, 0) end)
    m:route(pointer()); local ok, err = pcall(m.route, m, pointer("pointer_up"))
    eq(ok, false); eq(err, sentinel); eq(a:isPressed(), false); eq(m:getCapture(), nil)
  end)
end)
test("P13 removal from up callback prevents the deferred click", function()
  withManager(function(m, r, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("pointer_up", function() r:remove(a); r:add(a) end)
    m:route(pointer()); m:route(pointer("pointer_up")); eq(n, 0)
  end)
end)
test("P14 cancellation from up callback prevents the deferred click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("pointer_up", function() m:cancelAll("stopped") end)
    m:route(pointer()); m:route(pointer("pointer_up")); eq(n, 0); eq(a:isPressed(), false)
  end)
end)
test("P15 consuming up controls bubbling but does not cancel the default click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("pointer_up", function() return true end)
    m:route(pointer()); eq(m:route(pointer("pointer_up")), true); eq(n, 1)
  end)
end)
test("P16 explicit dispatcher cancellation prevents the deferred click", function()
  withManager(function(m, _, a, _, _, _, d)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("pointer_up", function() d:cancel() end)
    m:route(pointer()); m:route(pointer("pointer_up")); eq(n, 0)
  end)
end)
test("P17 a second pointer cannot replace the held button", function()
  withManager(function(m, _, a, b)
    local first, second = 0, 0
    a:on("click", function() first = first + 1 end)
    b:on("click", function() second = second + 1 end)
    m:route(pointer()); m:route(pointer("pointer_down", 5, 1, 0, "other"))
    eq(m:getCapture(), a); eq(a:isPressed(), true); eq(b:isPressed(), false)
    m:route(pointer("pointer_up", 5, 1, 0, "other"))
    eq(m:getCapture(), a); eq(first, 0); eq(second, 0)
    m:route(pointer("pointer_up"))
    eq(m:getCapture(), nil); eq(a:isPressed(), false); eq(first, 1); eq(second, 0)
  end)
end)
test("P18 overlay inserted before release prevents click through it", function()
  withManager(function(m, r, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); r:add(widget.new {width = 3, height = 2})
    m:route(pointer("pointer_up")); eq(n, 0); eq(a:isPressed(), false)
  end)
end)
test("P19 click preserves raw input and bubbles after release", function()
  withManager(function(m, r, a)
    local seen = ""; local up = pointer("pointer_up"); up.raw = table.pack("drop", nil, 7)
    a:on("click", function(_, e) eq(e.raw, up.raw); eq(e.target, a); seen = seen .. "a" end)
    r:on("click", function(_, e) eq(e.target, a); eq(e.currentTarget, r); seen = seen .. "r" end)
    m:route(pointer()); m:route(up); eq(seen, "ar"); eq(up.type, "pointer_up")
    m:route(pointer("pointer_up", 25, 10)); eq(seen, "ar")
  end)
end)
test("P20 close from down callback clears the visual state", function()
  withManager(function(m, _, a)
    a:on("pointer_down", function() m:close() end)
    m:route(pointer()); eq(a:isPressed(), false); eq(m:getCapture(), nil)
  end)
end)
test("P21 painter renders button text and its focused and pressed colors", function()
  local renderer, painter = import("ocgui.renderer"), import("ocgui.painter")
  local unicode = require("unicode")
  withManager(function(m, r, a)
    a:setText("X"); local bg, written, chosen = nil, false, nil
    local backend = {}
    function backend:getSize() return 30, 20 end
    function backend:setForeground() end
    function backend:setBackground(value) bg = value end
    function backend:fill() end
    function backend:set(x, y, value) if x == 1 and y == 1 then written = value:find("X", 1, true) ~= nil; chosen = bg end end
    local p = painter.new(r, renderer.new(backend, unicode))
    m:setFocus(a); p:render(); eq(written, true); eq(chosen, 0x335577)
    m:route(pointer()); p:render(); eq(chosen, 0x557799)
    m:route(pointer("pointer_up")); p:render(); eq(chosen, 0x335577)
  end)
end)

report.total = report.passed + report.failed
report.ok = report.failed == 0
print(string.format("SUMMARY: %d passed, %d failed, %d total", report.passed, report.failed, report.total))
