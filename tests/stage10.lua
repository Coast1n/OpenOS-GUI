test("S02 dirty first step renders without pulling an event", function()
  withApp(function(app, _, state, _, _, _, _, pulls)
    addButton(app); assert(app:open()); eq(app:step(), true)
    assert(count(state, "fill") > 0); eq(pulls(), 0)
