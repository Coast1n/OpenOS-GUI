end)
test("S03 an idle step pulls one signal using the supplied bound", function()
  withApp(function(app, _, _, _, enqueue, _, waits, pulls)
    assert(app:open()); assert(app:render()); enqueue(table.pack("unknown", nil, 7))
    eq(app:step(2), true); eq(pulls(), 1); eq(waits[1][1], 2)
  end)
end)
test("S04 an idle unbounded step forwards nil wait", function()
  withApp(function(app, _, _, _, enqueue, _, waits)
