test("S05 zero-timeout steps still pull at most one timeout result", function()
  withApp(function(app, _, _, _, enqueue, _, waits, pulls)
    assert(app:open()); assert(app:render()); enqueue(table.pack(nil))
    eq(app:step(0), true); eq(pulls(), 1); eq(waits[1][1], 0)
