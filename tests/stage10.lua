test("R06 callback errors remain primary when cleanup also fails", function()
  withApp(function(app, _, state, _, enqueue)
    local b = addButton(app)
    b:on("pointer_down", function() state.fail.setBackground = "once"; error("primary boom", 0) end)
    enqueue(touch()); local ok, err = app:run()
    eq(ok, nil); eq(err.code, "callback_failed"); eq(err.message, "primary boom"); assert(#err.cleanupErrors > 0)
    eq(state.buffer, 3); eq(state.blink, true); eq(app._state, "closed"); eq(app.root._interactionOwner, nil)
  end)
end)
