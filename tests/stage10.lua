end)
test("S10 stopping in a callback skips post-event drawing", function()
  withApp(function(app, _, state, _, enqueue)
    local b = addButton(app); b:on("pointer_down", function() app:stop() end)
    assert(app:open()); assert(app:render()); local fills = count(state, "fill"); enqueue(touch())
    eq(app:step(), false); eq(count(state, "fill"), fills); eq(b:isPressed(), false)
  end)
end)
test("S11 stopping inside pull prevents dispatch of the returned signal", function()
  withApp(function(app, _, _, _, enqueue)
    local b, n = addButton(app), 0; b:on("pointer_down", function() n = n + 1 end)
    assert(app:open()); assert(app:render())
    enqueue(function() app:stop(); return table.unpack(touch(), 1, 6) end)
    eq(app:step(), false); eq(n, 0)
  end)
end)
test("S12 interrupted exits a step normally", function()
  withApp(function(app, _, _, _, enqueue)
    assert(app:open()); assert(app:render()); enqueue(table.pack("interrupted"))
    eq(app:step(), false); eq(app:isActive(), false)
  end)
end)
test("S13 recursive steps are rejected during pull and callbacks", function()
  withApp(function(app, _, _, _, enqueue)
    local b = addButton(app)
    b:on("pointer_down", function() local active, err = app:step(); eq(active, nil); eq(err.code, "invalid_state") end)
    assert(app:open()); assert(app:render())
    enqueue(function()
      local active, err = app:step(); eq(active, nil); eq(err.code, "invalid_state")
      return table.unpack(touch(), 1, 6)
    end)
    eq(app:step(0), true); eq(app:isActive(), true)
  end)
end)
test("S14 invalid waits throw without breaking later steps", function()
  withApp(function(app)
    assert(app:open()); rejects(function() app:step(-1) end)
    rejects(function() app:step(math.huge) end); rejects(function() app:step("1") end)
    eq(app:step(0), true)
  end)
end)
