test("S06 each step processes only one queued keyboard signal", function()
  withApp(function(app, _, _, _, enqueue, _, _, pulls)
    local b, n = addButton(app), 0; b:on("click", function() n = n + 1 end)
    assert(app:open()); app:setFocus(b); assert(app:render()); enqueue(down()); enqueue(up())
    eq(app:step(0), true); eq(b:isPressed(), true); eq(n, 0); eq(pulls(), 1)
    eq(app:step(0), true); eq(b:isPressed(), false); eq(n, 1); eq(pulls(), 2)
  end)
end)
test("S07 wait stops at the interaction deadline and expires it", function()
  withApp(function(app, _, _, _, enqueue, clock, waits)
    local b = addButton(app); assert(app:open()); app:setFocus(b)
    app:dispatch(table.unpack(down(), 1, 5)); assert(app:render()); clock(4)
    enqueue(function(wait) eq(wait, 1); clock(5); return nil end)
    eq(app:step(10), true); eq(waits[1][1], 1); eq(b:isPressed(), false)
  end)
end)
test("S08 already-expired input clears and repaints without another pull", function()
  withApp(function(app, _, _, _, _, clock, _, pulls)
    local b = addButton(app); assert(app:open()); app:setFocus(b)
    app:dispatch(table.unpack(down(), 1, 5)); assert(app:render()); clock(5)
    eq(app:step(0), true); eq(b:isPressed(), false); eq(pulls(), 0)
  end)
end)
test("S09 a stopped step returns false without pulling", function()
  withApp(function(app, _, _, _, _, _, _, pulls)
