-- Keyboard-button checks with an injected clock; no hardware input.
local root = (...) or "."
assert(_VERSION == "Lua 5.3", "BLOCKED: Lua 5.3 required")
local import = assert(loadfile(root .. "/tests/support/loader.lua"))()(root)
local widget, container = import("ocgui.widget"), import("ocgui.container")
local button = import("ocgui.button")
local dispatcher, interaction = import("ocgui.dispatcher"), import("ocgui.interaction")
local report = {suite = "STAGE8-KEYBOARD-001", lua = _VERSION, passed = 0, failed = 0, cases = {}}
local function eq(a, b) assert(a == b, "expected " .. tostring(b) .. ", got " .. tostring(a)) end
local function rejects(fn) local ok = pcall(fn); eq(ok, false) end
local function approx(a, b) assert(math.abs(a - b) < 0.000001, "numeric mismatch") end
local function test(name, fn)
  local ok, err = pcall(fn)
  report[ok and "passed" or "failed"] = report[ok and "passed" or "failed"] + 1
  report.cases[#report.cases + 1] = {name = name, passed = ok, error = not ok and tostring(err) or nil}
  print((ok and "PASS " or "FAIL ") .. name .. (ok and "" or ": " .. tostring(err)))
end
local function pointer(kind, x, y, button, player, source)
  return {type = kind or "pointer_down", source = source or "screen", screenX = x or 1,
    screenY = y or 1, button = button or 0, player = player}
end
local function key(kind, code, source)
  return {type = kind, source = source or "keyboard-1", code = code, char = 0}
end
local function withManager(fn, oldHook)
  local r = container.new {width = 30, height = 20}
  local a = r:add(button.new {x = 1, width = 3, height = 2, focusable = true})
  local b = r:add(button.new {x = 5, width = 3, height = 2, focusable = true})
  local c = r:add(button.new {x = 9, width = 3, height = 2, focusable = true})
  r._onTreeChanged = oldHook
  local d, time = dispatcher.new(r), 0
  local m = interaction.new(r, d, function() return time end)
  local ok, err = pcall(fn, m, r, a, b, c, function(value) time = value end, d)
  local closed, closeErr = pcall(m.close, m)
  if not ok then error(err, 0) end
  if not closed then error(closeErr, 0) end
end

test("K01 Enter defaults precede key handlers and release before click", function()
  withManager(function(m, _, a)
    local seen = ""; m:setFocus(a)
    a:on("key_down", function() eq(a:isPressed(), true); seen = seen .. "d" end)
    a:on("key_up", function() eq(a:isPressed(), false); seen = seen .. "u" end)
    a:on("click", function() eq(a:isPressed(), false); seen = seen .. "c" end)
    m:route(key("key_down", 28)); eq(seen, "d")
    m:route(key("key_up", 28)); eq(seen, "duc"); eq(m:nextTimeout(), nil)
  end)
end)
test("K02 Space activates a focused button", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 57)); m:route(key("key_up", 57)); eq(n, 1)
  end)
end)
test("K03 repeated key-down does not repeat activation", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    for _ = 1, 5 do m:route(key("key_down", 28)) end
    eq(n, 0); m:route(key("key_up", 28)); eq(n, 1)
    m:route(key("key_up", 28)); eq(n, 1)
  end)
end)
test("K04 another keyboard cannot release the held activation", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(key("key_up", 28, "keyboard-2"))
    eq(a:isPressed(), true); eq(n, 0); m:route(key("key_up", 28)); eq(n, 1)
  end)
end)
test("K05 another player cannot release the held activation", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    local down, up = key("key_down", 28), key("key_up", 28)
    down.player, up.player = "p", "q"
    m:route(down); m:route(up); eq(a:isPressed(), true); eq(n, 0)
    up.player = "p"; m:route(up); eq(n, 1)
  end)
end)
test("K06 releasing a different key preserves the original activation", function()
  withManager(function(m, _, a)
    m:setFocus(a); m:route(key("key_down", 28)); m:route(key("key_up", 57))
    eq(a:isPressed(), true); m:route(key("key_up", 28)); eq(a:isPressed(), false)
  end)
end)
test("K07 an unmatched release does not click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_up", 28)); m:route(key("key_up", 57)); eq(n, 0)
  end)
end)
test("K08 moving focus cancels the old activation", function()
  withManager(function(m, _, a, b)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); m:setFocus(b); eq(a:isPressed(), false)
    m:setFocus(a); m:route(key("key_up", 28)); eq(n, 0)
  end)
end)
test("K09 hidden or disabled buttons cannot retain keyboard press", function()
  withManager(function(m, _, a)
    m:setFocus(a); m:route(key("key_down", 28)); a:setVisible(false); eq(a:isPressed(), false)
    m:route(key("key_up", 28)); a:setVisible(true); m:setFocus(a)
    m:route(key("key_down", 28)); a:setEnabled(false); eq(a:isPressed(), false)
  end)
end)
test("K10 detachment and reattachment cancels the activation", function()
  withManager(function(m, r, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); r:remove(a); r:add(a); m:setFocus(a)
    m:route(key("key_up", 28)); eq(a:isPressed(), false); eq(n, 0)
  end)
end)
test("K11 a lost key release expires without synthesizing click", function()
  withManager(function(m, _, a, _, _, clock)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); clock(4); eq(m:nextTimeout(10), 1); eq(m:nextTimeout(0), 0)
    clock(5); eq(m:expire(), true); eq(a:isPressed(), false); eq(m:nextTimeout(), nil)
    m:route(key("key_up", 28)); eq(n, 0)
  end)
end)
test("K12 repeated keys do not extend the five-second deadline", function()
  withManager(function(m, _, a, _, _, clock)
    m:setFocus(a); m:route(key("key_down", 57)); clock(4); m:route(key("key_down", 57))
    clock(5); eq(m:expire(), true); eq(a:isPressed(), false)
  end)
end)
test("K13 after timeout a full new press can activate", function()
  withManager(function(m, _, a, _, _, clock)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); clock(5); m:route(); m:route(key("key_down", 28))
    eq(a:isPressed(), false); m:route(key("key_up", 28))
    m:route(key("key_down", 28)); m:route(key("key_up", 28)); eq(n, 1)
  end)
end)
test("K14 left pointer-down cancels keyboard press and owns capture", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(pointer()); eq(m:getCapture(), a)
    m:route(key("key_up", 28)); eq(a:isPressed(), true); eq(n, 0)
    m:route(pointer("pointer_up")); eq(n, 1); eq(a:isPressed(), false)
  end)
end)
test("K15 keyboard cannot replace an active pointer press", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(pointer()); m:route(key("key_down", 28)); m:route(key("key_up", 28))
    eq(m:getCapture(), a); eq(a:isPressed(), true); eq(n, 0)
    m:route(pointer("pointer_up")); eq(n, 1)
  end)
end)
test("K16 interruption and screen changes cancel keyboard state", function()
  withManager(function(m, _, a)
    for _, kind in ipairs({"screen_resized", "interrupted"}) do
      m:setFocus(a); m:route(key("key_down", 28)); m:route {type = kind}
      eq(a:isPressed(), false); eq(m:getFocus(), nil); eq(m:nextTimeout(), nil)
    end
    m:setFocus(a); m:route(key("key_down", 28)); m:close()
    eq(a:isPressed(), false); eq(m:getFocus(), nil)
  end)
end)
test("K17 stopping from key-up cancels the deferred click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("key_up", function() m:cancelAll("stopped") end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(key("key_up", 28)); eq(n, 0)
  end)
end)
test("K18 consuming key-up does not cancel the default click", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("key_up", function() return true end); m:setFocus(a)
    m:route(key("key_down", 28)); eq(m:route(key("key_up", 28)), true); eq(n, 1)
  end)
end)
test("K19 explicit dispatcher cancellation suppresses activation", function()
  withManager(function(m, _, a, _, _, _, d)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("key_up", function() d:cancel() end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(key("key_up", 28)); eq(n, 0)
  end)
end)
test("K20 failing key-down handler clears press and preserves the error", function()
  withManager(function(m, _, a)
    local sentinel = {}; a:on("key_down", function() error(sentinel, 0) end); m:setFocus(a)
    local ok, err = pcall(m.route, m, key("key_down", 28))
    eq(ok, false); eq(err, sentinel); eq(a:isPressed(), false); eq(m:nextTimeout(), nil)
  end)
end)
test("K21 failing key-up handler cannot leave a held button", function()
  withManager(function(m, _, a)
    local n = 0; a:on("click", function() n = n + 1 end)
    a:on("key_up", function() error("up failed") end); m:setFocus(a)
    m:route(key("key_down", 28)); rejects(function() m:route(key("key_up", 28)) end)
    eq(a:isPressed(), false); eq(n, 0); eq(m:nextTimeout(), nil)
  end)
end)
test("K22 click callback errors leave clean state and allow recovery", function()
  withManager(function(m, _, a)
    local sentinel = {}; local off = a:on("click", function() error(sentinel, 0) end); m:setFocus(a)
    m:route(key("key_down", 28)); local ok, err = pcall(m.route, m, key("key_up", 28))
    eq(ok, false); eq(err, sentinel); eq(a:isPressed(), false); off()
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(key("key_down", 28)); m:route(key("key_up", 28)); eq(n, 1)
  end)
end)
test("K23 keyboard click preserves raw data and bubbles", function()
  withManager(function(m, r, a)
    local seen = ""; local up = key("key_up", 28); up.raw = table.pack("key_up", nil, 0, 28)
    a:on("click", function(_, e) eq(e.raw, up.raw); eq(e.code, 28); eq(e.screenX, nil); seen = seen .. "a" end)
    r:on("click", function(_, e) eq(e.target, a); seen = seen .. "r" end)
    m:setFocus(a); m:route(key("key_down", 28)); m:route(up); eq(seen, "ar"); eq(up.type, "key_up")
  end)
end)
test("K24 Tab cancels activation even when focus wraps to the same button", function()
  withManager(function(m, r, a, b, c)
    r:remove(b); r:remove(c); m:setFocus(a)
    local n = 0; a:on("click", function() n = n + 1 end)
    m:route(key("key_down", 28)); m:route(key("key_down", 15))
    eq(m:getFocus(), a); eq(a:isPressed(), false)
    m:route(key("key_up", 28)); eq(n, 0)
  end)
end)
test("K25 focusable ordinary widgets do not acquire button defaults", function()
  withManager(function(m, r)
    local a = r:add(widget.new {focusable = true}); local n = 0
    a:on("click", function() n = n + 1 end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(key("key_up", 28)); eq(n, 0); eq(m:nextTimeout(), nil)
  end)
end)
test("K26 a second activation key does not replace the first", function()
  withManager(function(m, _, a)
    local seen = {}; a:on("click", function(_, e) seen[#seen + 1] = e.code end); m:setFocus(a)
    m:route(key("key_down", 28)); m:route(key("key_down", 57)); m:route(key("key_up", 57))
    eq(a:isPressed(), true); m:route(key("key_up", 28)); eq(#seen, 1); eq(seen[1], 28)
  end)
end)

report.total = report.passed + report.failed
report.ok = report.failed == 0
print(string.format("SUMMARY: %d passed, %d failed, %d total", report.passed, report.failed, report.total))
return report
