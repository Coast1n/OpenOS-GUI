test("C03 matching release dispatches once and finalizes once", function()
  withManager(function(m, _, a)
    local up, finished = 0, 0
    a:on("pointer_up", function() eq(m:getCapture(), a); up = up + 1 end)
    m:capturePointer(a, pointer(), function(node, reason) eq(node, a); eq(reason, "released"); finished = finished + 1 end)
    m:route(pointer("pointer_up", 99, 99)); eq(m:getCapture(), nil)
    m:route(pointer("pointer_up", 99, 99)); eq(up, 1); eq(finished, 1)
  end)
end)
test("C04 another screen cannot release capture", function()
