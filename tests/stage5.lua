test("L10 closing inside focus notification prevents subsequent callbacks", function()
  withManager(function(m, _, a)
    local calls = 0
    a:on("focus", function() m:close() end)
    a:on("focus", function() calls = calls + 1 end)
    a:on("pointer_down", function() calls = calls + 1 end)
    eq(m:route(pointer()), false); eq(calls, 0); eq(m:getFocus(), nil)
  end)
