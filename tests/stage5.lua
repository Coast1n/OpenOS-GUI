  end)
end)
test("C10 timeout calculation respects the caller maximum", function()
  withManager(function(m, _, a)
    eq(m:nextTimeout(), nil); eq(m:nextTimeout(2), 2)
    m:capturePointer(a, pointer()); eq(m:nextTimeout(2), 2); eq(m:nextTimeout(10), 5)
    eq(m:nextTimeout(0), 0); rejects(function() m:nextTimeout(-1) end)
