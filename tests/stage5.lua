test("C13 a release callback error still releases capture and routing guards", function()
  withManager(function(m, _, a, b)
    local sentinel, finished = {}, 0
    a:on("pointer_up", function() error(sentinel, 0) end)
    m:capturePointer(a, pointer(), function() finished = finished + 1 end)
    local ok, err = pcall(function() m:route(pointer("pointer_up")) end)
    eq(ok, false); eq(err, sentinel); eq(m:getCapture(), nil); eq(finished, 1)
    m:route(pointer("pointer_down", 5, 1)); eq(m:getFocus(), b)
  end)
end)
test("C14 a finalizer error leaves no stale capture", function()
  withManager(function(m, _, a)
    local sentinel = {}
    m:capturePointer(a, pointer(), function() error(sentinel, 0) end)
    local ok, err = pcall(function() m:route(pointer("pointer_up")) end)
    eq(ok, false); eq(err, sentinel); eq(m:getCapture(), nil)
    eq(m:capturePointer(a, pointer()), true)
  end)
end)
test("C15 finalizers cannot start a replacement capture", function()
  withManager(function(m, _, a, b)
