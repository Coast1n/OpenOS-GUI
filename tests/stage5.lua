test("C07 inactivity times out without manufacturing a release", function()
  withManager(function(m, _, a, _, _, clock)
    local up, reason = 0
    a:on("pointer_up", function() up = up + 1 end)
    m:capturePointer(a, pointer(), function(_, why) reason = why end)
    clock(4.99); approx(m:nextTimeout(), 0.01); eq(m:getCapture(), a)
    clock(5); eq(m:expire(), true); eq(m:getCapture(), nil); eq(reason, "timeout"); eq(up, 0)
  end)
end)
test("C08 matching drag renews the inactivity deadline", function()
  withManager(function(m, _, a, _, _, clock)
