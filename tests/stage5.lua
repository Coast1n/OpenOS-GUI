test("L06 screen changes and interruptions silently clear all interaction", function()
  withManager(function(m, _, a, b)
    local reason, blurred = nil, 0
    a:on("blur", function() blurred = blurred + 1 end)
    m:route(key("key_down", 15)); eq(m:getFocus(), a)
    m:capturePointer(a, pointer(), function(_, why) reason = why end)
    m:route {type = "screen_resized", source = "screen", width = 30, height = 20}
    eq(reason, "screen_resized"); eq(m:getFocus(), nil); eq(m:getCapture(), nil); eq(blurred, 0)
    m:setFocus(b); m:capturePointer(b, pointer()); m:route {type = "interrupted"}
    eq(m:getFocus(), nil); eq(m:getCapture(), nil)
    m:route(key("key_down", 15)); eq(m:getFocus(), a)
    local focused = 0
    a:on("blur", function() m:cancelAll("stopped") end)
    b:on("focus", function() focused = focused + 1 end)
    m:setFocus(b); eq(m:getFocus(), nil); eq(focused, 0)
  end)
end)
test("L07 tree observers are chained and restored on idempotent close", function()
  local calls = 0
  local oldHook = function() calls = calls + 1 end
  withManager(function(m, r, a, _, _, _, d)
    a:setVisible(false); eq(calls, 1); assert(m:close()); assert(m:close())
    eq(r._onTreeChanged, oldHook); eq(r._interactionOwner, nil)
    local other = interaction.new(r, d, function() return 0 end); assert(other:close())
  end, oldHook)
end)
test("L08 cleanup errors still detach the manager and clear state", function()
