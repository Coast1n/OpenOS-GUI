-- Synthetic focus/capture checks with an injected clock; no hardware input.
local root = (...) or "."
assert(_VERSION == "Lua 5.3", "BLOCKED: Lua 5.3 required")
local import = assert(loadfile(root .. "/tests/support/loader.lua"))()(root)
local widget, container = import("ocgui.widget"), import("ocgui.container")
local dispatcher, interaction = import("ocgui.dispatcher"), import("ocgui.interaction")
local report = {suite = "STAGE5-INTERACTION-001", lua = _VERSION, passed = 0, failed = 0, cases = {}}
local function eq(a, b) assert(a == b, "expected " .. tostring(b) .. ", got " .. tostring(a)) end
local function rejects(fn) local ok = pcall(fn); eq(ok, false) end
local function approx(a, b) assert(math.abs(a - b) < 0.000001, "numeric mismatch") end
local function test(name, fn)
  local ok, err = pcall(fn)
  report[ok and "passed" or "failed"] = report[ok and "passed" or "failed"] + 1
  report.cases[#report.cases + 1] = {name = name, passed = ok, error = not ok and tostring(err) or nil}
  print((ok and "PASS " or "FAIL ") .. name .. (ok and "" or ": " .. tostring(err)))
end
local function pointer(kind, x, y, button, player, source)
  return {type = kind or "pointer_down", source = source or "screen", screenX = x or 1,
    screenY = y or 1, button = button or 0, player = player}
end
local function key(kind, code, source)
  return {type = kind, source = source or "keyboard-1", code = code, char = 0}
end
local function withManager(fn, oldHook)
  local r = container.new {width = 30, height = 20}
  local a = r:add(widget.new {x = 1, width = 3, height = 2, focusable = true})
  local b = r:add(widget.new {x = 5, width = 3, height = 2, focusable = true})
  local c = r:add(widget.new {x = 9, width = 3, height = 2, focusable = true})
  r._onTreeChanged = oldHook
  local d, time = dispatcher.new(r), 0
  local m = interaction.new(r, d, function() return time end)
  local ok, err = pcall(fn, m, r, a, b, c, function(value) time = value end, d)
  local closed, closeErr = pcall(m.close, m)
  if not ok then error(err, 0) end
  if not closed then error(closeErr, 0) end
end

test("F01 manager starts without focus or capture", function()
  withManager(function(m, r, _, _, _, _, d)
    eq(m:getFocus(), nil); eq(m:getCapture(), nil); eq(m:nextTimeout(), nil)
    rejects(function() interaction.new(r, d, function() return 0 end) end)
    rejects(function() interaction.new(r, d, nil) end)
  end)
end)
test("F02 focusability defaults and setters validate booleans", function()
  local a = widget.new(); eq(a:isFocusable(), false)
  eq(a:setFocusable(true), a); eq(a:isFocusable(), true)
  rejects(function() a:setFocusable(nil) end)
  rejects(function() widget.new {focusable = 1} end)
end)
test("F03 focus and blur are local and identify related targets", function()
  withManager(function(m, r, a, b)
    local seen = ""
    r:on("focus", function() seen = seen .. "root" end)
    a:on("focus", function(_, e) eq(e.target, a); eq(e.currentTarget, a); seen = seen .. "a+" end)
    a:on("blur", function(_, e) eq(e.relatedTarget, b); seen = seen .. "a-" end)
    b:on("focus", function(_, e) eq(e.relatedTarget, a); seen = seen .. "b+" end)
    m:setFocus(a); m:setFocus(b); eq(seen, "a+a-b+"); eq(m:getFocus(), b)
  end)
end)
test("F04 repeated focus does not notify or invalidate again", function()
  withManager(function(m, r, a)
    local calls = 0; a:on("focus", function() calls = calls + 1 end)
    m:setFocus(a); r._dirty = false; m:setFocus(a)
    eq(calls, 1); eq(r._dirty, false)
  end)
end)
test("F05 forward focus traversal wraps", function()
