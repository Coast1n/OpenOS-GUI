-- Pure widget-tree checks; no GPU, term, event or unicode modules are needed.
local root = (...) or "."
assert(_VERSION == "Lua 5.3", "BLOCKED: Lua 5.3 required")
local import = assert(loadfile(root .. "/tests/support/loader.lua"))()(root)
local widget, container = import("ocgui.widget"), import("ocgui.container")
local report = {suite = "STAGE3-TREE-001", lua = _VERSION, passed = 0, failed = 0, cases = {}}
local function eq(actual, expected)
  assert(actual == expected, "expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function rejects(callback)
  local ok = pcall(callback); eq(ok, false)
end
local function rect(object, x, y, width, height, absolute)
  local a, b, c, d
  if absolute then a, b, c, d = object:getAbsoluteBounds()
  else a, b, c, d = object:getBounds() end
  eq(a, x); eq(b, y); eq(c, width); eq(d, height)
end
local function test(name, callback)
  local ok, err = pcall(callback)
  report[ok and "passed" or "failed"] = report[ok and "passed" or "failed"] + 1
  report.cases[#report.cases + 1] = {name = name, passed = ok, error = not ok and tostring(err) or nil}
  print((ok and "PASS " or "FAIL ") .. name .. (ok and "" or ": " .. tostring(err)))
end
local function box(x, y, width, height)
  return container.new {x = x or 1, y = y or 1, width = width or 20, height = height or 10}
end

test("W01 default state and independent styles", function()
  local a, b = widget.new(), widget.new()
  rect(a, 1, 1, 1, 1); eq(a:isVisible(), true); eq(a:isEnabled(), true)
  eq(a:getParent(), nil); eq(widget.is(a), true); eq(widget.is({}), false)
  a:setStyle {foreground = 7}; eq(b:getStyle().foreground, nil)
end)
test("W02 invalid constructor types and flags", function()
  for _, options in ipairs({false, 0, "x", {x = false}, {width = "2"}, {visible = 1}, {enabled = "yes"}}) do
    rejects(function() widget.new(options) end)
  end
end)
test("W03 dimensions are positive integers", function()
  for _, size in ipairs({0, -1, 1.5, math.huge}) do
    rejects(function() widget.new {width = size} end)
    rejects(function() widget.new {height = size} end)
  end
end)
test("W04 negative positions and false flags are preserved", function()
  local a = widget.new {x = -3, y = 0, width = 2, height = 3, visible = false, enabled = false}
  rect(a, -3, 0, 2, 3); eq(a:isVisible(), false); eq(a:isEnabled(), false)
end)
test("W05 setBounds is chainable and atomic on validation failure", function()
  local a = widget.new()
  eq(a:setBounds(2, 3, 4, 5), a); rect(a, 2, 3, 4, 5)
  rejects(function() a:setBounds(4, 5, 0, 6) end); rect(a, 2, 3, 4, 5)
end)
test("W06 styles are copied on construction, set and get", function()
  local style = {foreground = 7, active = {background = 8}}
  local a = widget.new {style = style}
  style.active.background = 1; eq(a:getStyle().active.background, 8)
  local read = a:getStyle(); read.active.background = 2; eq(a:getStyle().active.background, 8)
  eq(a:setStyle(style), a); style.active.background = 3; eq(a:getStyle().active.background, 1)
end)
test("W07 cyclic and unsupported styles are rejected atomically", function()
  local a = widget.new {style = {foreground = 7}}
  local cyclic = {}; cyclic.active = cyclic
  for _, style in ipairs({cyclic, {[1] = 3}, {draw = function() end}, {foreground = 0/0}}) do
    rejects(function() a:setStyle(style) end); eq(a:getStyle().foreground, 7)
  end
  rejects(function() a:setStyle(nil) end)
end)
test("W08 shared acyclic style branches are copied independently", function()
  local shared = {foreground = 7}
  local a = widget.new {style = {normal = shared, active = shared}}
  local read = a:getStyle(); read.normal.foreground = 1; eq(read.active.foreground, 7)
end)
test("W09 visible and enabled setters validate boolean values", function()
  local a = widget.new()
  eq(a:setVisible(false):setEnabled(false), a)
  rejects(function() a:setVisible(nil) end); rejects(function() a:setEnabled(0) end)
  eq(a:isVisible(), false); eq(a:isEnabled(), false)
end)
test("W10 plain widget hit testing uses half-open boundaries", function()
  local a = widget.new {x = 2, y = 3, width = 4, height = 2}
  eq(a:hitTest(2, 3), a); eq(a:hitTest(5, 4), a)
  eq(a:hitTest(6, 4), nil); eq(a:hitTest(5, 5), nil); eq(a:hitTest(1, 3), nil)
end)
test("W11 coordinate validation catches overflow", function()
  rejects(function() widget.new {x = math.maxinteger} end)
  local parent = box(math.maxinteger - 10, 1, 5, 5)
  local child = parent:add(widget.new {x = 20})
  rejects(function() child:getAbsoluteBounds() end)
end)
test("W12 minimum integer local coordinate does not wrap", function()
  local parent = box(2, 1, 2, 2)
  local child = parent:add(widget.new {x = math.mininteger})
  rect(child, math.mininteger + 1, 1, 1, 1, true)
  eq(child:getClipBounds(), nil)
end)

test("T01 add returns child and assigns parent", function()
  local parent, child = box(), widget.new()
  eq(parent:add(child), child); eq(child:getParent(), parent)
  eq(parent:getChildren()[1], child); eq(widget.is(parent), true)
end)
test("T02 reject arbitrary objects and duplicate insertion", function()
  local parent, child = box(), widget.new()
  rejects(function() parent:add({}) end); parent:add(child)
  rejects(function() parent:add(child) end); eq(#parent:getChildren(), 1)
end)
test("T03 reparenting requires explicit removal", function()
  local a, b, child = box(), box(), widget.new()
  a:add(child); rejects(function() b:add(child) end)
  eq(a:remove(child), child); eq(b:add(child), child); eq(child:getParent(), b)
end)
test("T04 reject self and ancestor cycles", function()
  local a, b = box(), box()
  rejects(function() a:add(a) end); a:add(b)
  rejects(function() b:add(a) end); eq(a:getParent(), nil); eq(b:getParent(), a)
end)
test("T05 removal preserves subtree and local coordinates", function()
  local a, b = box(), box(3, 4)
  local child = b:add(widget.new {x = 2, y = 3})
  a:add(b); eq(a:remove(b), b)
  eq(b:getParent(), nil); eq(child:getParent(), b); rect(child, 2, 3, 1, 1)
end)
test("T06 removing an absent child is a no-op", function()
  local a, child = box(), widget.new()
  a._dirty = false; eq(a:remove(child), nil); eq(a._dirty, false)
end)
test("T07 child snapshots cannot mutate the tree", function()
  local a, b, c = box(), widget.new(), widget.new()
  a:add(b); a:add(c)
  local children = a:getChildren(); children[1] = nil
  eq(a:getChildren()[1], b); eq(a:getChildren()[2], c)
end)
test("T08 nested coordinates are parent-relative", function()
  local a, b = box(4, 5), box(3, 2)
  a:add(b); local child = b:add(widget.new {x = 2, y = 3, width = 2})
  rect(child, 7, 8, 2, 1, true); rect(child, 2, 3, 2, 1)
end)
test("T09 moving an ancestor updates descendant coordinates", function()
  local a, b = box(), box(3, 2)
  a:add(b); local child = b:add(widget.new {x = 2})
  a:setBounds(5, 6, 20, 10); rect(child, 8, 7, 1, 1, true)
end)
test("T10 clipping intersects all ancestors", function()
  local a = box(1, 1, 5, 5)
  local b = a:add(box(4, 4, 5, 5))
  local child = b:add(widget.new {width = 4, height = 4})
  local clip = child:getClipBounds(); eq(clip.x, 4); eq(clip.y, 4); eq(clip.width, 2); eq(clip.height, 2)
  eq(child:hitTest(5, 5), child); eq(child:hitTest(6, 5), nil)
  clip.width = 100; eq(child:getClipBounds().width, 2)
end)
test("T11 wholly clipped descendants cannot be hit", function()
  local a = box(1, 1, 5, 5)
  local child = a:add(widget.new {x = 6, width = 4})
  eq(child:getClipBounds(), nil); eq(child:hitTest(6, 1), nil); eq(a:hitTest(6, 1), nil)
end)
test("T12 topmost child wins overlapping hit tests", function()
  local a = box(); local b = a:add(widget.new()); local c = a:add(widget.new())
  eq(a:hitTest(1, 1), c); a:remove(c); eq(a:hitTest(1, 1), b)
  a:add(c); eq(a:hitTest(1, 1), c)
end)
test("T13 hiding a top child reveals the lower child", function()
  local a = box(); local b = a:add(widget.new()); local c = a:add(widget.new())
  c:setVisible(false); eq(a:hitTest(1, 1), b); c:setVisible(true); eq(a:hitTest(1, 1), c)
end)
test("T14 disabled top child blocks click-through", function()
  local a = box(); a:add(widget.new()); local c = a:add(widget.new {enabled = false})
  eq(a:hitTest(1, 1), c); eq(c:isEnabled(), false)
end)
test("T15 inherited visibility preserves child-local flags", function()
  local a = box(); local b = a:add(widget.new {visible = false}); local c = a:add(widget.new())
  a:setVisible(false); eq(c:isVisible(), false); eq(c:getClipBounds(), nil)
  a:setVisible(true); eq(b:isVisible(), false); eq(c:isVisible(), true)
end)
test("T16 disabled container blocks its descendants", function()
  local a = box(); local b = a:add(box()); local c = b:add(widget.new())
  b:setEnabled(false); eq(c:isEnabled(), false); eq(a:hitTest(1, 1), b)
  b:setEnabled(true); eq(c:isEnabled(), true); eq(a:hitTest(1, 1), c)
end)
test("T17 empty container remains a hit candidate", function()
  local a = box(); eq(a:hitTest(10, 5), a); eq(a:hitTest(21, 5), nil)
end)
test("T18 descendant mutations invalidate the ancestor chain", function()
  local a, b = box(), box(); a:add(b); local c = b:add(widget.new())
  a._dirty, b._dirty, c._dirty = false, false, false
  c:setBounds(2, 2, 1, 1); eq(a._dirty, true); eq(b._dirty, true); eq(c._dirty, true)
end)
test("T19 no-op setters do not request another redraw", function()
  local a = widget.new(); a._dirty = false
  a:setBounds(1, 1, 1, 1):setVisible(true):setEnabled(true)
  eq(a._dirty, false)
end)
test("T20 detached invalidation no longer reaches the former root", function()
  local a = box(); local b = a:add(widget.new()); local notifications = 0
  a._onInvalidate = function() notifications = notifications + 1 end
  a:remove(b); eq(notifications, 1); b:setEnabled(false); eq(notifications, 1)
end)
test("T21 internal mutation guard rejects changes before commit", function()
  local a = box(); local b = a:add(widget.new()); local c = widget.new()
  a._mutationGuard = function() error("drawing in progress") end
  rejects(function() b:setBounds(2, 2, 1, 1) end)
  rejects(function() a:add(c) end); rejects(function() a:remove(b) end)
  rect(b, 1, 1, 1, 1); eq(b:getParent(), a); eq(c:getParent(), nil)
end)
test("T22 application root cannot be edited or attached as a child", function()
  local a = box(); a._isApplicationRoot = true
  rejects(function() a:setBounds(1, 1, 2, 2) end)
  rejects(function() a:setVisible(false) end); rejects(function() a:setEnabled(false) end)
  rejects(function() box():add(a) end)
end)
test("T23 removal notifies the old root with the detached subtree", function()
  local a = box(); local b = a:add(box()); local notifications = {}
  a._onTreeChanged = function(node, kind) notifications[#notifications + 1] = {node, kind, node:getParent()} end
  b:setVisible(false); a:remove(b)
  eq(notifications[1][1], b); eq(notifications[1][2], "visible")
  eq(notifications[2][1], b); eq(notifications[2][2], "removed"); eq(notifications[2][3], nil)
end)

report.total = report.passed + report.failed
report.ok = report.failed == 0
print(string.format("SUMMARY: %d passed, %d failed, %d total", report.passed, report.failed, report.total))
return report
